function exKey(s) {
  return String(s ?? '').toLowerCase().replace(/\s+/g, '');
}
const EX_INFO = new Map();    // 정식 이름 키 → { name, part, met }
const EX_ALIAS = new Map();   // 다른 이름 키 → 정식 이름 키
for (const [name, part, aliases, met] of EXERCISES) {
  const key = exKey(name);
  EX_INFO.set(key, { name, part, met: met ?? null, aliases });
  for (const a of aliases) EX_ALIAS.set(exKey(a), key);
}
