// 자동완성에 띄울 이름 (표시용, 띄어쓰기 살림)
const FOOD_NAMES = Object.keys(FOOD_DB);

(function mergeFoodTables() {
  const norm = (n) => String(n).toLowerCase().replace(/\s+/g, '');
  const unitsFor = (kind, grams) => Object.fromEntries((KIND_UNITS[kind] || KIND_UNITS.p).map((u) => [u, grams]));
  for (const [name, kcal100, protein, grams, kind] of MFDS_FOODS) {
    const key = norm(name);
    const hand = Object.hasOwn(FOOD_DB, key) ? FOOD_DB[key] : null;
    if (hand?.keep) continue;
    // 손으로 적은 낱개 단위(개·줄·장…)는 살리고, 1인분 단위(그릇·인분…)는 식약처 1인분이 덮는다 (뒤에 펼친 쪽이 이김).
    // 마실 것은 반대: 식약처 음료 1인분은 카페 음료 크기(350ml 안팎)라 우유 1잔(200ml)엔 손으로 적은 게 맞다.
    const units = kind === 'd' ? { ...unitsFor(kind, grams), ...(hand?.units || {}) } : { ...(hand?.units || {}), ...unitsFor(kind, grams) };
    FOOD_DB[key] = { kcal100, protein, units, kind, src: 'mfds' };
    if (!hand) FOOD_NAMES.push(name);
  }
  for (const [alias, target] of FOOD_ALIASES) {
    const key = norm(alias);
    if (!Object.hasOwn(FOOD_DB, key) && Object.hasOwn(FOOD_DB, norm(target))) {
      FOOD_DB[key] = FOOD_DB[norm(target)];
      FOOD_NAMES.push(alias);
    }
  }
  // 끝말 평균은 자동완성엔 안 띄운다 ("찌개"만 골라 적을 일은 없다)
  for (const [suffix, kcal100, protein, grams, kind] of GENERIC_FOODS) {
    if (!Object.hasOwn(FOOD_DB, suffix)) FOOD_DB[suffix] = { kcal100, protein, units: unitsFor(kind, grams), kind, generic: true };
  }
})();
